import Foundation

extension CGFloat {
    enum spacing {
        /// Figma: spacing/none — 0pt
        static let none: CGFloat = 0
        
        /// Figma: spacing/small — 8pt
        static let small: CGFloat = 8
        
        /// Figma: spacing/medium — 16pt
        static let medium: CGFloat = 16
        
        /// Figma: spacing/large — 32pt
        static let large: CGFloat = 32
    }
}
